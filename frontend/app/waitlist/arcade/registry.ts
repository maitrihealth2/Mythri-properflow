export function getFeaturedGame(): GameMetadata {
  // Deterministic daily rotation by day of the year
  const now = new Date()
  const start = new Date(now.getFullYear(), 0, 0)
  const diff = now.getTime() - start.getTime()
  const dayOfYear = Math.floor(diff / (1000 * 60 * 60 * 24))
  const index = dayOfYear % GAME_REGISTRY.length
  return GAME_REGISTRY[index]
}
